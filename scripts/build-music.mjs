// Builds one extra music track (2026-11-19): the night music and the dungeon music.
//   node scripts/build-music.mjs night "<open-space.mp3>" --trim-end=6
//   node scripts/build-music.mjs dungeon "<fsm-team-above-the-clouds-loop.wav>" --seamless
// - public/audio/<name>.m4a: the track, matched in loudness to the island music (overworld.m4a,
//   about -17.8 LUFS), made into a loop, with half a second of the loop on each side as padding
//   (the same layout as build-audio.mjs, so the game loops it sample-exactly).
// - src/music-loops.ts: each track's loop points, merged with the ones already there.
// --seamless loops the file as it is (a "loop" version whose end runs straight into its start).
// Otherwise its last 3 seconds are crossfaded into its first 3. --trim-end=N drops the last N
// seconds first (a track that fades out at its end).
// Both tracks: FSM Team, free-stock-music.com, credit required. The sources stay outside the repo.
import { execFileSync, spawnSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const args = process.argv.slice(2)
const [name, src] = args.filter((a) => !a.startsWith('--'))
const seamless = args.includes('--seamless')
const trimEnd = Number(args.find((a) => a.startsWith('--trim-end='))?.split('=')[1] ?? 0)
if (!name || !src) {
  console.error('usage: node scripts/build-music.mjs <name> <source> [--seamless] [--trim-end=N]')
  process.exit(1)
}
const TARGET = -17.8 // LUFS, the island music's measured loudness
const X = 3 // crossfade seconds
const PAD = 0.5
const ff = (...a) => execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...a])
const dur = (f) => Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString().trim())
/** Integrated loudness in LUFS (ffmpeg's ebur128 summary, which it prints to stderr). */
function loudness(f) {
  const r = spawnSync('ffmpeg', ['-hide_banner', '-nostats', '-i', f, '-af', 'ebur128=framelog=quiet', '-f', 'null', '-'], { encoding: 'utf8' })
  const m = r.stderr.match(/^\s+I:\s+(-?\d+(?:\.\d+)?) LUFS/m)
  if (!m) throw new Error(`could not measure ${f}`)
  return Number(m[1])
}

const tmp = mkdtempSync(join(tmpdir(), 'island-music-'))
const root = new URL('..', import.meta.url).pathname
const gain = +(TARGET - loudness(src)).toFixed(2)

// the source, trimmed and levelled, as float PCM
const base = join(tmp, 'base.wav')
const total0 = dur(src)
ff('-i', src, '-t', String(total0 - trimEnd), '-af', `volume=${gain}dB`, '-ar', '44100', '-c:a', 'pcm_f32le', base)
const total = dur(base)

// one cycle of the loop
let L = total
let loop = base
if (!seamless) {
  L = total - X
  loop = join(tmp, 'loop.wav')
  ff(
    '-i', base,
    '-filter_complex',
    [
      `[0:a]asplit=3[a][b][c]`,
      `[a]atrim=0:${X},asetpts=PTS-STARTPTS,afade=t=in:d=${X}:curve=qsin[head]`,
      `[b]atrim=${L}:${total},asetpts=PTS-STARTPTS,afade=t=out:d=${X}:curve=qsin[tail]`,
      `[head][tail]amix=inputs=2:normalize=0:duration=first[mix]`,
      `[c]atrim=${X}:${L},asetpts=PTS-STARTPTS[body]`,
      `[mix][body]concat=n=2:v=0:a=1[out]`,
    ].join(';'),
    '-map', '[out]', '-c:a', 'pcm_f32le', loop,
  )
}
// half a second of the loop's end before it and of its start after it
ff(
  '-i', loop,
  '-filter_complex',
  [
    `[0:a]asplit=3[a][b][c]`,
    `[a]atrim=${L - PAD}:${L},asetpts=PTS-STARTPTS[pre]`,
    `[c]atrim=0:${PAD},asetpts=PTS-STARTPTS[post]`,
    `[pre][b][post]concat=n=3:v=0:a=1[out]`,
  ].join(';'),
  '-map', '[out]', '-c:a', 'aac', '-b:a', '112k', join(root, `public/audio/${name}.m4a`),
)

// merge the loop points into src/music-loops.ts
const file = join(root, 'src/music-loops.ts')
const loops = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8').match(/LOOPS = (\{[\s\S]*?\n\})/)?.[1] ?? '{}') : {}
loops[name] = { start: PAD, end: +(PAD + L).toFixed(4) }
writeFileSync(
  file,
  `// Generated by scripts/build-music.mjs. Night and dungeon music: FSM Team (free-stock-music.com).
/** Each extra track's loop: it plays from 0, then loops between these points (seconds). */
export const LOOPS = ${JSON.stringify(loops, null, 2)}
`,
)
console.log(name, `gain ${gain} dB, loop ${L.toFixed(2)} s`)
