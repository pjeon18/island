def main():
    sheet = Image.open(sys.argv[1]).convert('RGBA')
    root = Path(__file__).resolve().parent.parent
    crops = {}
    for name, (x, y, w, h, trim) in PIECES.items():
        c = sheet.crop((x, y, x + w, y + h))
        if trim:
            c = c.crop(c.getbbox())
        crops[name] = c
    # shelf-pack into a 256-wide atlas, tallest first
    order = sorted(crops, key=lambda n: (-crops[n].height, n))
    W = 256
    x = y = shelf = 0
    rects = {}
    for n in order:
        c = crops[n]
        if x + c.width > W:
            x, y, shelf = 0, y + shelf + 1, 0
        rects[n] = (x, y, c.width, c.height)
        x += c.width + 1
        shelf = max(shelf, c.height)
    atlas = Image.new('RGBA', (W, y + shelf), (0, 0, 0, 0))
    for n, (x, y, w, h) in rects.items():
        atlas.paste(crops[n], (x, y))
    out = root / 'public' / 'art'
    out.mkdir(parents=True, exist_ok=True)
    atlas.save(out / 'nature.png', optimize=True)
    lines = ',\n'.join(f"  '{n}': {list(rects[n])}" for n in sorted(rects))
    (root / 'src' / 'nature-atlas.ts').write_text(
        '// Generated by scripts/build-nature.py from Flurmimon\'s "Tileset - Nature" (DeviantArt; credit\n'
        '// required, non-commercial). [x, y, w, h] in public/art/nature.png.\n'
        f'export const NATURE_ATLAS: Record<string, [number, number, number, number]> = {{\n{lines},\n}}\n'
    )
    print(f'{len(rects)} pieces, atlas {W}x{atlas.height}')


if __name__ == '__main__':
    main()
