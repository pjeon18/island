// Builds the game's audio from the sources Paul supplied (2026-11-12):
//   node scripts/build-audio.mjs "<Cute & Cozy UI Audio Free Sample folder>" "<Ambient Music.wav>"
// - public/audio/sfx.m4a: the chosen UI sounds, mono, in one sprite file (the pack's licence
//   forbids shipping its original files for separate download, so they are never copied as-is)
// - public/audio/overworld.m4a: the island music, made into a seamless loop by crossfading its
//   last 2 seconds into its first 2, with half a second of the loop on each side as padding
// - src/audio-sprite.ts: where each sound sits in the sprite, and the music's loop points
// Needs ffmpeg and ffprobe. The sources stay outside the repo.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync, readFileSync, mkdirSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const [pack, music] = process.argv.slice(2)
if (!pack || !music) {
  console.error('usage: node scripts/build-audio.mjs <sfx pack folder> <music wav>')
  process.exit(1)
}
// our name → the pack's file
const SOUNDS = {
  open: 'Menu_Open',
  close: 'Menu_Close',
  tab: 'Highlight',
  click: 'Clicked_In',
  blip: 'Dialogue_Blip',
  speak: 'Dialogue_Expression',
  buy: 'Purchase',
  coin: 'Currency',
  confirm: 'Confirm',
  cancel: 'Cancel',
  success: 'Success',
  unlock: 'Unlock',
  start: 'Unpause',
  pause: 'Pause',
  warn: 'Warning',
  give: 'Sell',
  fail: 'Failure',
}
const GAP = 0.3 // seconds of silence between sounds (and before the first)
const RATE = 44100
const ff = (...args) => execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...args])
const dur = (f) => Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString().trim())

const tmp = mkdtempSync(join(tmpdir(), 'island-audio-'))
const root = new URL('..', import.meta.url).pathname
mkdirSync(join(root, 'public/audio'), { recursive: true })

// ---------- the sound sprite ----------
// each sound as mono 16-bit PCM, then one raw stream: silence, sound, silence, sound …
const silence = Buffer.alloc(Math.round(GAP * RATE) * 2)
const parts = [silence]
const sprite = {}
let at = GAP
for (const [name, file] of Object.entries(SOUNDS)) {
  const raw = join(tmp, `${name}.raw`)
  ff('-i', join(pack, 'Sounds', `${file}.wav`), '-ac', '1', '-ar', String(RATE), '-f', 's16le', raw)
  const pcm = readFileSync(raw)
  const len = pcm.length / 2 / RATE
  sprite[name] = [+at.toFixed(4), +len.toFixed(4)]
  parts.push(pcm, silence)
  at += len + GAP
}
const all = Buffer.concat(parts)
// where the first sound becomes audible, so the game can correct for the encoder's delay
let onset = 0
for (let i = 0; i < all.length / 2; i++)
  if (Math.abs(all.readInt16LE(i * 2)) > 600) {
    onset = i / RATE
    break
  }
writeFileSync(join(tmp, 'sfx.raw'), all)
ff('-f', 's16le', '-ar', String(RATE), '-ac', '1', '-i', join(tmp, 'sfx.raw'), '-c:a', 'aac', '-b:a', '96k', join(root, 'public/audio/sfx.m4a'))

// ---------- the music loop ----------
const X = 2 // crossfade seconds
const PAD = 0.5
const total = dur(music)
const L = total - X
const loop = join(tmp, 'loop.wav')
ff(
  '-i', music,
  '-filter_complex',
  [
    `[0:a]asplit=3[a][b][c]`,
    `[a]atrim=0:${X},asetpts=PTS-STARTPTS,afade=t=in:d=${X}:curve=qsin[head]`,
    `[b]atrim=${L}:${total},asetpts=PTS-STARTPTS,afade=t=out:d=${X}:curve=qsin[tail]`,
    `[head][tail]amix=inputs=2:normalize=0:duration=first[mix]`,
    `[c]atrim=${X}:${L},asetpts=PTS-STARTPTS[body]`,
    `[mix][body]concat=n=2:v=0:a=1[out]`,
  ].join(';'),
  '-map', '[out]', '-c:a', 'pcm_f32le', loop,
)
// half a second of the loop's end before it and of its start after it, so a decoder that
// shifts the audio a little still lands inside continuous music at the loop points
ff(
  '-i', loop,
  '-filter_complex',
  [
    `[0:a]asplit=3[a][b][c]`,
    `[a]atrim=${L - PAD}:${L},asetpts=PTS-STARTPTS[pre]`,
    `[c]atrim=0:${PAD},asetpts=PTS-STARTPTS[post]`,
    `[pre][b][post]concat=n=3:v=0:a=1[out]`,
  ].join(';'),
  '-map', '[out]', '-c:a', 'aac', '-b:a', '128k', join(root, 'public/audio/overworld.m4a'),
)

writeFileSync(
  join(root, 'src/audio-sprite.ts'),
  `// Generated by scripts/build-audio.mjs. Sounds: Case Portman Audio (Cute & Cozy UI Audio, free sample).
export const SPRITE = ${JSON.stringify(sprite, null, 2)} as const
export type SfxName = keyof typeof SPRITE
/** When the first sound becomes audible in sfx.m4a, before any encoder delay. */
export const SPRITE_ONSET = ${onset.toFixed(5)}
/** The music's loop: it plays from 0, then loops between these points (seconds). */
export const MUSIC_LOOP = { start: ${PAD}, end: ${+(PAD + L).toFixed(4)} }
`,
)
console.log('sfx', Object.keys(sprite).length, 'sounds,', at.toFixed(2), 's; music loop', L, 's')
